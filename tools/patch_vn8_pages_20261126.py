def patch(path, pairs, banner):
    src = open(path, encoding='utf-8').read()
    orig = src
    for old, new, cnt in pairs:
        n = src.count(old)
        if n != cnt:
            raise SystemExit('[%s] 기대 %d회 · 실제 %d회: %r' % (banner, cnt, n, old[:110]))
        src = src.replace(old, new)
