    '현금도 <strong>2027-04-01~07-31 122일이 판매 중단</strong>이었다가 2027-08-01 부터 다시 열립니다(6번이 전면 판매 중단 후 재개로 확인). '
    '<strong>TPEWH 는 2026-12-31 1박 20,416,237원</strong>으로 창 안 최고가이고, <strong>2027-05-26~06-03 컴퓨텍스 기간</strong>이 '
